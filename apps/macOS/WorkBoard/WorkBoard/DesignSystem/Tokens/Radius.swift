/// Corner radii of the design system (`radius-*` tokens), in points.
/// Glass controls and avatars use a capsule or circle (`radius-full`).
enum Radius {
    /// `radius-xs`: tasks, fields, menu rows, content buttons.
    static let xs = 6.0
    /// `radius-sm`: board cards and menus.
    static let sm = 10.0
    /// `radius-md`: lists.
    static let md = 12.0
    /// `radius-lg`: modals.
    static let lg = 16.0
}
