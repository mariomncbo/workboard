/// Spacing scale of the design system (`space-*` tokens), in points.
enum Spacing {
    /// `space-1`: between tasks; between icon and text.
    static let s1 = 4.0
    /// `space-2`: between related controls (HIG); task padding.
    static let s2 = 8.0
    /// `space-3`: list and card padding; between lists.
    static let s3 = 12.0
    /// `space-5`: window margins and between groups (HIG).
    static let s5 = 20.0
    /// `space-7`: between sections of Home.
    static let s7 = 28.0
    /// `space-10`: distance from the floating bar to the bottom edge.
    static let s10 = 40.0
}
